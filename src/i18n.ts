export type Locale = keyof typeof catalogs;
export type Messages = {
  [
    Key in keyof (typeof catalogs)["en"]
  ]: (typeof catalogs)["en"][Key] extends string
    ? string
    : {
        [Nested in keyof (typeof catalogs)["en"][Key]]: string;
      };
};

export function systemLocale(language: string): Locale {
  return language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function preferredLocale(
  stored: string | null,
  language: string,
): Locale {
  return stored === "zh-CN" || stored === "en"
    ? stored
    : systemLocale(language);
}
