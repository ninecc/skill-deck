export type Locale = keyof typeof catalogs;
export type Messages = {
  [Key in keyof (typeof catalogs)["en"]]: string;
};

export function systemLocale(locale: string): Locale {
  return locale.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function preferredLocale(stored: string | null, locale: string): Locale {
  return stored === "en" || stored === "zh-CN" ? stored : systemLocale(locale);
}
